using System;
using System.Globalization;
using System.Text;
using System.Web;
using System.Web.UI;
using System.Web.UI.WebControls;
using ForteLogisticsApp.Security;
using ForteLogisticsApp.Services;

namespace ForteLogisticsApp.Controls
{
    /// <summary>
    /// The report footer: who generated the report, in what role, and when, plus a
    /// confidentiality note. On screen it closes the report; in print the same line is also
    /// stamped into the bottom margin of EVERY page next to "Page X of Y" (CSS @page margin
    /// boxes - supported by Chrome and Edge; other browsers simply omit the page stamp, while
    /// this on-page footer still prints at the end).
    ///
    /// The name comes from the signed-in session, never from the request, and is CSS-escaped
    /// before it goes into the style rule, so it cannot break out of the string or the element.
    /// </summary>
    public partial class ReportFooter : UserControl
    {
        protected Literal litFooter;

        /// <summary>Optional extra note, e.g. how a cohort figure is defined.</summary>
        public string Note { get; set; }

        protected override void OnPreRender(EventArgs e)
        {
            base.OnPreRender(e);

            var secure = Page as SecurePage;
            string name = secure != null && secure.FullName.Length > 0 ? secure.FullName : "Unknown user";
            string role = DescribeRole(secure);
            string stamp = DateTime.Now.ToString("yyyy/MM/dd HH:mm", CultureInfo.InvariantCulture);
            string generated = "Generated by " + name + " (" + role + ") on " + stamp;

            var sb = new StringBuilder();
            sb.Append("<footer class='lc-report-footer'>")
              .Append("<div><span class='material-symbols-outlined' aria-hidden='true'>badge</span>")
              .Append(HttpUtility.HtmlEncode(generated)).Append("</div>")
              .Append("<div>Logisticore Courier Service &middot; Internal management information &middot; ")
              .Append("figures are computed from live operational data</div>");
            if (!string.IsNullOrEmpty(Note))
            {
                sb.Append("<div class='lc-report-note'>").Append(HttpUtility.HtmlEncode(Note)).Append("</div>");
            }
            sb.Append("</footer>");

            // Per-page print stamp on the named "lc-report" page only (Styles/reports.css puts
            // .lc-report content on that page), so other printouts - waybills, invoices - keep
            // their own layout. Only the dynamic text lives here; its styling and the page
            // counter are in the stylesheet.
            sb.Append("<style>@page lc-report { @bottom-left { content: \"")
              .Append(UiHelper.CssStringEnc(generated + " | Logisticore Courier Service"))
              .Append("\"; } }</style>");

            litFooter.Text = sb.ToString();
        }

        private static string DescribeRole(SecurePage page)
        {
            if (page == null) return "User";
            // Case-insensitive, matching how SecurePage compares roles everywhere else.
            switch ((page.Role ?? string.Empty).ToLowerInvariant())
            {
                case "admin": return "Administrator";
                case "customer": return "Customer";
                case "staff": return SecurePage.IsDriver(page.UserId) ? "Driver" : "Operations Staff";
                default: return "User";
            }
        }
    }
}
